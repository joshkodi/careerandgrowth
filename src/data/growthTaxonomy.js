export function isValidSignalId(signalId) {
  return Boolean(signals[signalId])
}

export function isValidTraitId(traitId) {
  return Boolean(traits[traitId])
}

export function isValidDomainId(domainId) {
  return Boolean(domains[domainId])
}

export function isValidPathwayId(pathwayId) {
  return Boolean(pathways[pathwayId])
}

export function isValidCareerFamilyId(careerFamilyId) {
  return Boolean(careerFamilies[careerFamilyId])
}

export function getConfidenceLevel(score = 0) {
  const safeScore = Math.max(
    0,
    Math.min(100, Number(score) || 0)
  )

  return (
    confidenceLevels.find(
      (level) =>
        safeScore >= level.minScore &&
        safeScore <= level.maxScore
    ) || confidenceLevels[0]
  )
}

//
// Development-time taxonomy validation.
//
// This gives us an easy way later to detect:
// - invalid signal references
// - invalid trait references
// - invalid domain references
// - pathway weights that do not total 1.0
//

export function validateGrowthTaxonomy() {
  const errors = []

  Object.values(traits).forEach((trait) => {
    Object.keys(trait.signalWeights || {}).forEach(
      (signalId) => {
        if (!signals[signalId]) {
          errors.push(
            `Trait "${trait.id}" references unknown signal "${signalId}".`
          )
        }
      }
    )
  })

  Object.values(pathways).forEach((pathway) => {
    Object.keys(pathway.traitWeights || {}).forEach(
      (traitId) => {
        if (!traits[traitId]) {
          errors.push(
            `Pathway "${pathway.id}" references unknown trait "${traitId}".`
          )
        }
      }
    )

    Object.keys(pathway.domainWeights || {}).forEach(
      (domainId) => {
        if (!domains[domainId]) {
          errors.push(
            `Pathway "${pathway.id}" references unknown domain "${domainId}".`
          )
        }
      }
    )

    const traitWeightTotal = Object.values(
      pathway.traitWeights || {}
    ).reduce((total, weight) => total + weight, 0)

    const domainWeightTotal = Object.values(
      pathway.domainWeights || {}
    ).reduce((total, weight) => total + weight, 0)

    const totalWeight =
      traitWeightTotal + domainWeightTotal

    if (Math.abs(totalWeight - 1) > 0.0001) {
      errors.push(
        `Pathway "${pathway.id}" weights total ${totalWeight.toFixed(
          4
        )} instead of 1.0.`
      )
    }
  })

  Object.values(careerFamilies).forEach(
    (careerFamily) => {
      careerFamily.pathwayIds.forEach((pathwayId) => {
        if (!pathways[pathwayId]) {
          errors.push(
            `Career family "${careerFamily.id}" references unknown pathway "${pathwayId}".`
          )
        }
      })
    }
  )

  return {
    valid: errors.length === 0,
    errors,
  }
}

